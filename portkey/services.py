"""Service wiring: builds every repository and component once per app (package 0, frozen).

Routes reach services through ``api.deps.ServicesDep``; WebSocket handlers use
``ws.app.state.services``. Constructors here do no I/O, so stub implementations can be wired
before they work; ``startup`` opens and migrates the database. Packages fill in the classes
named here and do not edit this file (a new dependency is a contract change: report it).
"""

from __future__ import annotations

from dataclasses import dataclass

from portkey.config import Config
from portkey.interfaces import (
    AppAuth,
    ConnectionsRepo,
    DismissedSuggestions,
    EventLog,
    GroupsRepo,
    HostKeyStore,
    KeyProvider,
    KeysMetaRepo,
    KeyVault,
    KnownHostsReader,
    SettingsRepo,
    SshConnector,
    TagsRepo,
    TokenStore,
)
from portkey.keys.discovery import FsKeyProvider
from portkey.keys.known_hosts import FileKnownHosts
from portkey.keys.vault import MemoryKeyVault
from portkey.security.auth import PasswordAuth
from portkey.security.tokens import SqliteTokenStore
from portkey.sessions.registry import MemorySessionRegistry
from portkey.ssh.chain import ChainConnector
from portkey.store.connections import SqliteConnectionsRepo
from portkey.store.db import Database
from portkey.store.events import SqliteEventLog
from portkey.store.groups import SqliteGroupsRepo
from portkey.store.hostkeys import SqliteDismissedSuggestions, SqliteHostKeyStore
from portkey.store.keys_meta import SqliteKeysMetaRepo
from portkey.store.settings import SqliteSettingsRepo
from portkey.store.tags import SqliteTagsRepo
from portkey.wizard.install import InstallWizard


@dataclass(slots=True)
class Services:
    config: Config
    db: Database
    connections: ConnectionsRepo
    groups: GroupsRepo
    tags: TagsRepo
    host_keys: HostKeyStore
    dismissed: DismissedSuggestions
    settings: SettingsRepo
    events: EventLog
    keys_meta: KeysMetaRepo
    vault: KeyVault
    keys: KeyProvider
    known_hosts: KnownHostsReader
    tokens: TokenStore
    auth: AppAuth
    connector: SshConnector
    sessions: MemorySessionRegistry
    wizard: InstallWizard

    async def startup(self) -> None:
        self.db.migrate()
        await self.sessions.start()

    async def shutdown(self) -> None:
        try:
            await self.sessions.aclose()
        finally:
            self.db.close()


def build_services(config: Config) -> Services:
    limits = config.limits
    db = Database(config.db_path)
    connections = SqliteConnectionsRepo(db, limits)
    settings = SqliteSettingsRepo(db)
    events = SqliteEventLog(db)
    keys_meta = SqliteKeysMetaRepo(db)
    host_keys = SqliteHostKeyStore(db)
    vault = MemoryKeyVault()
    keys = FsKeyProvider(config, keys_meta, settings, vault)
    known_hosts = FileKnownHosts(config.known_hosts_path)
    tokens = SqliteTokenStore(db, limits.token_ttl, max_age=limits.token_max_age)
    connector = ChainConnector(
        connections, keys, host_keys, known_hosts, events, settings, limits, vault=vault
    )
    return Services(
        config=config,
        db=db,
        connections=connections,
        groups=SqliteGroupsRepo(db, limits),
        tags=SqliteTagsRepo(db),
        host_keys=host_keys,
        dismissed=SqliteDismissedSuggestions(db),
        settings=settings,
        events=events,
        keys_meta=keys_meta,
        vault=vault,
        keys=keys,
        known_hosts=known_hosts,
        tokens=tokens,
        auth=PasswordAuth(db, tokens),
        connector=connector,
        sessions=MemorySessionRegistry(connector, connections, settings, events, limits),
        wizard=InstallWizard(connector, connections, keys, events),
    )
